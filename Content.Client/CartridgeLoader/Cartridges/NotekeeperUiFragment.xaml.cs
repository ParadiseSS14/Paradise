using System.Linq;
using System.Numerics;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Tweens;
using Content.Client.UserInterface.Tweens.Builders;
using Content.Client.UserInterface.Tweens.Easers;
using Content.Client.UserInterface.Tweens.Extensions;
using Content.Shared.Hands;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NotekeeperUiFragment : BoxContainer
{
    private Label? _noNotesLabel;

    public event Action<string>? OnNoteAdded;
    public event Action<string>? OnNoteRemoved;

    public NotekeeperUiFragment()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        Input.OnTextEntered += _ =>
        {
            AddNote(Input.Text);
            OnNoteAdded?.Invoke(Input.Text);
            Input.Clear();
        };

        UpdateState(new List<string>());
    }

    public void UpdateState(List<string> notes)
    {
        MessageContainer.RemoveAllChildren();

        foreach (var note in notes)
        {
            AddNote(note);
        }

        if (MessageContainer.ChildCount == 0)
        {
            _noNotesLabel = new Label()
            {
                Name = "NoNotesLabel",
                Text = Loc.GetString("notekeeper-no-notes"),
                VerticalAlignment = VAlignment.Center,
                HorizontalAlignment = HAlignment.Center,
                StyleClasses = { "LabelSubtext" },
            };

            MessageContainer.AddChild(_noNotesLabel);
        }
    }

    private void AddNote(string note)
    {
        var rowHolder = new PanelContainer()
        {
            HorizontalExpand = true,
            StyleClasses = { "SurfacePrimary" },
        };

        var row = new BoxContainer();
        row.HorizontalExpand = true;
        row.Orientation = LayoutOrientation.Horizontal;
        row.Margin = new Thickness(4);
        row.VerticalAlignment = VAlignment.Center;

        var label = new RichTextLabel();
        label.Text = note;
        label.HorizontalExpand = true;

        var removeButton = new TextureButton();
        removeButton.TexturePath = "/Textures/Interface/Nano/cross.svg.png";
        removeButton.AddStyleClass(StyleClass.SubColored);
        removeButton.VerticalAlignment = VAlignment.Center;
        removeButton.SetSize = new Vector2(12, 12);
        removeButton.OnPressed += _ => OnNoteRemoved?.Invoke(label.Text);

        rowHolder.AddChild(row);
        row.AddChild(label);
        row.AddChild(removeButton);

        MessageContainer.AddChild(rowHolder);
    }
}
