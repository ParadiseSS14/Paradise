using Content.Client.GameTicking.Managers;
using Content.Shared.Coordinates;
using Content.Shared.GameTicking;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Player;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.UserInterface.Controls;

[GenerateTypedNameReferences]
public sealed partial class RoundInfo : BoxContainer
{
    [Dependency] private IGameTiming _gameTiming = default!;
    [Dependency] private IEntitySystemManager _entitySystem = default!;
    [Dependency] private IPlayerManager _playerMan = default!;
    [Dependency] private IEntityManager _entityManager = default!;
    private ClientGameTicker? _gameTicker;

    public RoundInfo()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        // I didn't want to do a =?? check in update. This checks it less, so.
        _entitySystem.SystemLoaded += OnSystemLoaded;
    }

    private void OnSystemLoaded(object? sender, SystemChangedArgs e)
    {
        if (e.System is not ClientGameTicker ticker)
            return;
        _gameTicker = ticker;
        _entitySystem.SystemLoaded -= OnSystemLoaded;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        SetRoundTimer();
        SetPlayerCount();
        if (string.IsNullOrEmpty(MapNameValue.Text))
            SetMapName(_playerMan.LocalEntity);
    }

    private void SetRoundTimer()
    {
        if (_gameTicker == null)
            return;
        var stationTime = _gameTiming.CurTime.Subtract(_gameTicker.RoundStartTimeSpan);
        var time = $"{(int)stationTime.TotalHours:00}:{stationTime:mm\\:ss}";
        RoundTimerValue.Text = time;
    }

    private void SetPlayerCount()
    {
        PlayerCountValue.Text = _playerMan.PlayerCount.ToString();
    }

    private void SetMapName(EntityUid? player)
    {
        if (player == null)
            return;
        if (!_entityManager.TryGetComponent<TransformComponent>(player, out var xform))
            return;

        var mapUid = xform.MapUid;

        if (mapUid is not { } uid ||
            !_entityManager.TryGetComponent<MetaDataComponent>(uid, out var metadata))
            return;

        MapNameValue.Text = metadata.EntityName;
    }
}
